"""Write the int8 model as a C header the firmware compiles in."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from ridcheck.features import FEATURE_NAMES, N_FEATURES, WINDOW
from ridcheck.quantize import QuantModel


def _c_array(values, ctype: str, name: str, per_line: int = 16) -> str:
    flat = np.asarray(values).reshape(-1)
    body = []
    for start in range(0, len(flat), per_line):
        chunk = ", ".join(str(int(v)) for v in flat[start : start + per_line])
        body.append(f"    {chunk}")
    joined = ",\n".join(body)
    return f"static const {ctype} {name}[{len(flat)}] = {{\n{joined}\n}};"


def _c_float(value) -> str:
    """Hex float literal that round-trips the float32 the host multiplied with."""
    exact = float(np.float32(value))
    return exact.hex() + "f"


def _c_floats(values, name: str, per_line: int = 8) -> str:
    flat = np.asarray(values, dtype=np.float64).reshape(-1)
    body = []
    for start in range(0, len(flat), per_line):
        chunk = ", ".join(_c_float(v) for v in flat[start : start + per_line])
        body.append(f"    {chunk}")
    joined = ",\n".join(body)
    return f"static const float {name}[{len(flat)}] = {{\n{joined}\n}};"


def render_header(model: QuantModel, selftest: dict) -> str:
    layer1, layer2, layer3 = model.layers
    lines = [
        "/* Generated by ridcheck.export. Do not edit by hand. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define SD_WINDOW {WINDOW}",
        f"#define SD_FEATURES {N_FEATURES}",
        f"#define SD_INPUTS {WINDOW * N_FEATURES}",
        f"#define SD_H1 {layer1.out_features}",
        f"#define SD_H2 {layer2.out_features}",
        f"#define SD_THRESHOLD {model.threshold:.8e}f",
        "",
        "/* Feature order, oldest fix first, time-major:",
        " * " + ", ".join(FEATURE_NAMES),
        " */",
        _c_floats(model.feature_scale, "sd_feature_scale"),
        "",
        _c_array(layer1.weight, "int8_t", "sd_w1"),
        _c_array(layer1.bias, "int32_t", "sd_b1"),
        f"static const int32_t sd_m1 = {layer1.mult};",
        "",
        _c_array(layer2.weight, "int8_t", "sd_w2"),
        _c_array(layer2.bias, "int32_t", "sd_b2"),
        f"static const int32_t sd_m2 = {layer2.mult};",
        "",
        _c_array(layer3.weight, "int8_t", "sd_w3"),
        _c_array(layer3.bias, "int32_t", "sd_b3"),
        f"static const float sd_scale_acc3 = {_c_float(layer3.scale_acc)};",
        "",
        f"#define SD_N_SELFTEST {len(selftest['prob'])}",
        _c_floats(selftest["features"], "sd_selftest_feat"),
        _c_array(selftest["quantized"], "int8_t", "sd_selftest_q"),
        _c_array(selftest["acc"], "int32_t", "sd_selftest_acc"),
        _c_floats(selftest["prob"], "sd_selftest_p"),
        "",
    ]
    return "\n".join(lines) + "\n"


def write_header(model: QuantModel, selftest: dict, path: Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_header(model, selftest))


def save_quant(model: QuantModel, path: Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    layer1, layer2, layer3 = model.layers
    np.savez(
        path,
        feature_scale=model.feature_scale,
        threshold=np.array([model.threshold], dtype=np.float32),
        w1=layer1.weight, b1=layer1.bias, m1=np.array([layer1.mult], dtype=np.int32),
        w2=layer2.weight, b2=layer2.bias, m2=np.array([layer2.mult], dtype=np.int32),
        w3=layer3.weight, b3=layer3.bias,
        scale_acc3=np.array([layer3.scale_acc], dtype=np.float32),
    )


def load_quant(path: Path) -> QuantModel:
    from ridcheck.quantize import QuantLayer, QuantModel as Loaded

    data = np.load(path)
    layers = [
        QuantLayer(data["w1"], data["b1"], int(data["m1"][0]), 0.0, True),
        QuantLayer(data["w2"], data["b2"], int(data["m2"][0]), 0.0, True),
        QuantLayer(data["w3"], data["b3"], 0, float(data["scale_acc3"][0]), False),
    ]
    return Loaded(layers, data["feature_scale"], float(data["threshold"][0]))
